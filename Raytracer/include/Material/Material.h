#ifndef RAYTRACER_MATERIAL_H
#define RAYTRACER_MATERIAL_H

#include "Color.h"

struct Ray;
struct HitInfo;

/**
 * Defines how an object is rendered.
 */
class Material
{
public:
	virtual ~Material() = default;

	/**
	 * Computes the scattering behavior of an incoming ray.
	 *
	 * Implemented by concrete materials to determine whether
	 * an incoming ray is scattered and how its color contribution
	 * and outgoing direction are calculated.
	 *
	 * @param rayIn Incoming ray.
	 * @param hitInfo Surface intersection information.
	 * @param attenuation Output color attenuation applied to the ray.
	 * @param scattered Output ray generated by the material.
	 * @return True if the ray is scattered, false if it is absorbed.
	 */
	virtual bool Scatter(const Ray& rayIn, const HitInfo& hitInfo, Color& attenuation, Ray& scattered) const = 0;
};

#endif // RAYTRACER_MATERIAL_H